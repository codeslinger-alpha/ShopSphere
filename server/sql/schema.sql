-- One open request per order line. A rejected one is not open, which is what lets
-- a customer whose return was refused ask again; the quantity trigger above is
-- what stops the requests that ARE open from adding up to more than they bought.
--
-- Oracle has no partial index, so the predicate moves into the key: a CASE that
-- yields the order line for an open request and NULL for a closed one. Oracle
-- does not index a key that is entirely NULL, so closed requests drop out of the
-- index rather than colliding in it — the same rule, spelled the way this
-- database can spell it.
CREATE UNIQUE INDEX idx_product_returns_open ON product_returns(
    CASE WHEN status IN ('requested', 'approved', 'collected') THEN order_id END,
    CASE WHEN status IN ('requested', 'approved', 'collected') THEN prod_id END
)
