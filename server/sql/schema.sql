-- What a customer may return, and how much of it.
--
-- Two rules, both of which the API also states as a sentence but neither of which
-- the API is trusted to be the only enforcer of:
--
--   1. Only a delivered order can be returned. This is what makes a return and a
--      cancellation provably disjoint — CANCEL_ORDER requires 'pending' — so the
--      stock restore in fn_cleanup_cancelled_order and the restock here can never
--      both fire for the same unit.
--   2. The units returned across all of a customer's accepted requests for one
--      listing cannot exceed what they bought. Without this, three separate
--      requests of two units each on an order of three would restock six.
--      Rejected requests do not count: a customer whose return was refused is
--      entitled to ask again.
--
-- A compound trigger again. Counting a customer's other requests for the same
-- listing means reading product_returns, which the row being written belongs to,
-- so the reading waits until the statement that wrote it is over. The new row is
-- then already in the table and has to be excluded by hand — which is what
-- `LNNVL(r.return_id = ...)` does, and what PostgreSQL spelled
-- `return_id IS DISTINCT FROM NEW.return_id`.
CREATE OR REPLACE TRIGGER trg_check_return_quantity
FOR INSERT OR UPDATE ON product_returns
COMPOUND TRIGGER
    TYPE return_rows IS TABLE OF product_returns%ROWTYPE INDEX BY PLS_INTEGER;
    pending_rows return_rows;
    n PLS_INTEGER := 0;

    BEFORE EACH ROW IS
    BEGIN
        n := n + 1;
        pending_rows(n).return_id := :NEW.return_id;
        pending_rows(n).order_id  := :NEW.order_id;
        pending_rows(n).prod_id   := :NEW.prod_id;
        pending_rows(n).quantity  := :NEW.quantity;
        pending_rows(n).status    := :NEW.status;
    END BEFORE EACH ROW;

    AFTER STATEMENT IS
        v_ordered NUMBER;
        v_state   VARCHAR2(20 CHAR);
        v_already NUMBER;
    BEGIN
        FOR i IN 1 .. n LOOP
            BEGIN
                SELECT oi.quantity, o.order_status
                INTO v_ordered, v_state
                FROM order_items oi
                JOIN orders o ON o.order_id = oi.order_id
                WHERE oi.order_id = pending_rows(i).order_id
                  AND oi.prod_id = pending_rows(i).prod_id;
            EXCEPTION WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20004, 'That listing is not on that order.');
            END;

            IF v_state <> 'delivered' THEN
                RAISE_APPLICATION_ERROR(-20005, 'Only a delivered order can be returned.');
            END IF;

            SELECT COALESCE(SUM(r.quantity), 0) INTO v_already
            FROM product_returns r
            WHERE r.order_id = pending_rows(i).order_id
              AND r.prod_id = pending_rows(i).prod_id
              AND r.status <> 'rejected'
              AND LNNVL(r.return_id = pending_rows(i).return_id);

            -- A rejected request claims nothing, so the new row only counts against
            -- the order line when it is not itself a rejection. Without this test a
            -- refusal recorded while another request was open would be refused in
            -- turn, on the strength of units it never asked for.
            IF pending_rows(i).status <> 'rejected'
               AND v_already + pending_rows(i).quantity > v_ordered THEN
                RAISE_APPLICATION_ERROR(-20006,
                    'A customer cannot return more units than they bought of that listing.');
            END IF;
        END LOOP;
    END AFTER STATEMENT;
END;
/

-- Restrict order lifecycle transitions.
CREATE OR REPLACE TRIGGER trg_guard_order_transition
BEFORE UPDATE ON orders FOR EACH ROW
BEGIN
    IF (:OLD.order_status <> :NEW.order_status OR (:OLD.order_status IS NULL) <> (:NEW.order_status IS NULL))
       AND NOT (
        (:OLD.order_status = 'pending' AND :NEW.order_status IN ('shipped', 'cancelled')) OR
        (:OLD.order_status = 'shipped' AND :NEW.order_status IN ('pending', 'delivered'))
    ) THEN
        RAISE_APPLICATION_ERROR(-20007, 'That order status transition is not allowed.');
    END IF;
END;
/

-- What PostgreSQL enforced with a deferred constraint trigger, and Oracle has no
-- equivalent of: a master product may only be 'available' once every attribute
-- its category requires has a value.
--
-- The two halves cannot be checked in one statement, which is why PostgreSQL
-- deferred the check to the commit — the API writes the master, then its values,
-- and an immediate check would refuse the first write of a perfectly good pair.
-- Oracle deferrs constraints, not triggers, and this is not a constraint.
--
-- So the check lives where the commit does: adminCatalogController runs
-- q.INCOMPLETE_MASTER, the same predicate, as the last statement of saveMaster
-- and saveCategory. A direct SQL writer can still record an incomplete master;
-- nothing in the API can.
CREATE OR REPLACE VIEW incomplete_masters AS
SELECT mp.master_prod_id, mp.name, a.name AS attribute_name
FROM master_products mp
JOIN category_attributes ca ON ca.category_id = mp.category_id
JOIN attributes a ON a.attribute_id = ca.attribute_id
LEFT JOIN attribute_values av
    ON av.master_prod_id = mp.master_prod_id AND av.attribute_id = ca.attribute_id
WHERE mp.active_status = 'available'
  AND (av.attrib_value IS NULL OR TRIM(av.attrib_value) IS NULL);
/

