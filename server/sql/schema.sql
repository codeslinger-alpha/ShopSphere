-- A real multi-table workflow, called by the delivery API inside a transaction.
-- The guarded transition makes retries safe; a failure rolls back all three writes.
--
-- The courier is paid the order's own delivery_cost rather than a fee computed
-- here. That is the same number the customer was charged, and reading it back
-- from the row means the pay constants in orderQueries.js govern new orders only.
--
-- A procedure, where PostgreSQL wrote a procedure with an INOUT JSONB. Oracle's
-- caller cannot see a return value from a procedure, so the JSON this builds is
-- an OUT bind — which is why the API calls this from an anonymous block rather
-- than as a statement in its own right.
--
-- Every money figure is TO_CHARed to two places before it goes into the JSON.
-- PostgreSQL said `total_amount::text` and got "25.00" from a numeric(12,2);
-- Oracle's implicit conversion would say "25".
CREATE OR REPLACE PROCEDURE settle_delivery(
    p_order_id   IN  NUMBER,
    p_courier_id IN  NUMBER,
    p_result     OUT CLOB
) IS
    v_order_id      orders.order_id%TYPE;
    v_order_status  orders.order_status%TYPE;
    v_delivered_at  orders.delivered_at%TYPE;
    v_total_amount  orders.total_amount%TYPE;
    v_delivery_cost orders.delivery_cost%TYPE;
    v_courier_id    orders.delivery_person_id%TYPE;
    v_payment       CLOB;
    v_courier       CLOB;
BEGIN
    p_result := NULL;

    BEGIN
        UPDATE orders
        SET order_status = 'delivered', delivered_at = LOCALTIMESTAMP
        WHERE order_id = p_order_id AND delivery_person_id = p_courier_id
          AND order_status = 'shipped'
        RETURNING order_id, order_status, delivered_at, total_amount,
                  delivery_cost, delivery_person_id
        INTO v_order_id, v_order_status, v_delivered_at, v_total_amount,
             v_delivery_cost, v_courier_id;
        IF SQL%ROWCOUNT = 0 THEN RETURN; END IF;
    END;

    UPDATE payments SET payment_status = 'completed', paid_at = v_delivered_at
    WHERE order_id = p_order_id AND payment_status = 'pending';

    SELECT JSON_OBJECT(
        'transaction_id' VALUE transaction_id,
        'payment_status' VALUE payment_status,
        'paid_at'        VALUE TO_CHAR(paid_at, 'YYYY-MM-DD"T"HH24:MI:SS')
        RETURNING CLOB)
    INTO v_payment
    FROM payments WHERE order_id = p_order_id;

    UPDATE delivery_personnel
    SET earnings = COALESCE(earnings, 0) + ROUND(v_delivery_cost, 2)
    WHERE delivery_person_id = p_courier_id;

    SELECT JSON_OBJECT(
        'delivery_person_id' VALUE delivery_person_id,
        'earnings'           VALUE TO_CHAR(earnings, 'FM9999999990.00')
        RETURNING CLOB)
    INTO v_courier
    FROM delivery_personnel WHERE delivery_person_id = p_courier_id;

    -- Pay each shop for its own lines, in full. There is no commission between
    -- the customer's payment and the shop, and the delivery charge on this order
    -- is the courier's, not the shop's. One statement for however many shops the
    -- order spans: PostgreSQL grouped a joined subquery, which Oracle expresses
    -- as a correlated one.
    --
    -- A sale credits the balance when it is delivered, not when it is placed: an
    -- order still in a van is not money the shop can spend on stock.
    --
    -- The shop is named by its table for the same reason as above: SET takes a
    -- bare column name, so there is no alias for the correlated subquery to use.
    UPDATE shops
    SET balance = balance + (
        SELECT COALESCE(SUM(oi.quantity * oi.unit_price), 0)
        FROM order_items oi
        JOIN products p ON p.prod_id = oi.prod_id
        WHERE oi.order_id = p_order_id AND p.shop_id = shops.shop_id)
    WHERE EXISTS (
        SELECT 1 FROM order_items oi
        JOIN products p ON p.prod_id = oi.prod_id
        WHERE oi.order_id = p_order_id AND p.shop_id = shops.shop_id);

    SELECT JSON_OBJECT(
        'order_id'           VALUE v_order_id,
        'order_status'       VALUE v_order_status,
        'delivered_at'       VALUE TO_CHAR(v_delivered_at, 'YYYY-MM-DD"T"HH24:MI:SS'),
        'total_amount'       VALUE TO_CHAR(v_total_amount, 'FM9999999990.00'),
        'delivery_cost'      VALUE TO_CHAR(v_delivery_cost, 'FM9999999990.00'),
        'delivery_person_id' VALUE v_courier_id,
        'payment'            VALUE v_payment FORMAT JSON,
        'courier_earnings'   VALUE v_courier FORMAT JSON
        RETURNING CLOB) INTO p_result FROM dual;
END;
