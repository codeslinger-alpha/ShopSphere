-- =========================================================
-- 2. Keep orders.total_amount in sync with order_items
--    ("--for calculating order.total_amount")
--
--    A compound trigger, where PostgreSQL had an after-row one. The reason is
--    Oracle's mutating-table rule: a row trigger on order_items may not read
--    order_items, and fn_order_subtotal does exactly that. Collecting the
--    affected orders as the rows go by and summing them once the statement is
--    over is both legal here and one statement where PostgreSQL wrote one per
--    row.
-- =========================================================
CREATE OR REPLACE TRIGGER trg_order_items_recalc_total
FOR INSERT OR UPDATE OR DELETE ON order_items
COMPOUND TRIGGER
    TYPE order_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    touched order_ids;
    n PLS_INTEGER := 0;

    PROCEDURE remember(p_order_id NUMBER) IS
    BEGIN
        IF p_order_id IS NOT NULL THEN
            n := n + 1;
            touched(n) := p_order_id;
        END IF;
    END;

    AFTER EACH ROW IS
    BEGIN
        IF INSERTING OR UPDATING THEN remember(:NEW.order_id); END IF;
        IF DELETING OR UPDATING THEN remember(:OLD.order_id); END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT IS
    BEGIN
        FOR i IN 1 .. n LOOP
            UPDATE orders SET total_amount = fn_order_subtotal(touched(i))
            WHERE order_id = touched(i);
        END LOOP;
    END AFTER STATEMENT;
END;
/

-- =========================================================
-- 3. Disable a user when their role is removed
--    ("user_role ... on delete set null -- call a trigger to disable user")
-- =========================================================
CREATE OR REPLACE TRIGGER trg_disable_user_on_role_removal
BEFORE UPDATE ON users FOR EACH ROW
WHEN (NEW.user_role IS NULL AND OLD.user_role IS NOT NULL)
BEGIN
    :NEW.active_status := 'disabled';
END;
/

-- =========================================================
-- 4. Discontinue all of a shop's products when the shop is disabled
--    ("active_status ... -- when disabled, call a trigger to set product(discontinued) to true")
-- =========================================================
CREATE OR REPLACE TRIGGER trg_discontinue_products_on_shop_disable
AFTER UPDATE ON shops FOR EACH ROW
WHEN (NEW.active_status = 'disabled' AND OLD.active_status <> 'disabled')
BEGIN
    UPDATE products SET discontinued = 1 WHERE shop_id = :NEW.shop_id;
END;
/

-- =========================================================
-- 5. Free up affected orders when a courier goes "unavailable"
--    ("active_status ... -- when :new.active_status='unavailable' when order
--      still 'shipped' or 'pending', set orders.delivery_person_id:=null
--      and order_status:='pending'")
-- =========================================================
CREATE OR REPLACE TRIGGER trg_release_orders_on_personnel_unavailable
AFTER UPDATE ON delivery_personnel FOR EACH ROW
WHEN (NEW.active_status = 'unavailable' AND OLD.active_status <> 'unavailable')
BEGIN
    UPDATE orders
    SET delivery_person_id = NULL,
        order_status = 'pending'
    WHERE delivery_person_id = :NEW.delivery_person_id
      AND order_status IN ('shipped', 'pending');
END;
/

-- =========================================================
-- 6. Clean up an order when it's cancelled
--    Preserve the purchase history and return reserved stock once.
--
--    A BEFORE trigger, where PostgreSQL had an AFTER one, for one reason:
--    clearing the courier is a change to the very row being cancelled, and an
--    after-row trigger may not update its own table. Writing it into :NEW is how
--    a BEFORE row trigger says the same thing.
-- =========================================================
CREATE OR REPLACE TRIGGER trg_cleanup_cancelled_order
BEFORE UPDATE ON orders FOR EACH ROW
WHEN (NEW.order_status = 'cancelled' AND OLD.order_status <> 'cancelled')
BEGIN
    :NEW.delivery_person_id := NULL;

    -- The listing is named by its table rather than by an alias: Oracle's SET
    -- clause takes a bare column name, so there is no `p` to write on the left
    -- and the subqueries correlate through the table name instead.
    UPDATE products
    SET in_stock = in_stock + (
        SELECT SUM(oi.quantity) FROM order_items oi
        WHERE oi.order_id = :NEW.order_id AND oi.prod_id = products.prod_id)
    WHERE EXISTS (
        SELECT 1 FROM order_items oi
        WHERE oi.order_id = :NEW.order_id AND oi.prod_id = products.prod_id);

    UPDATE payments SET payment_status = 'failed', paid_at = NULL
    WHERE order_id = :NEW.order_id AND payment_status = 'pending';
END;
/

-- =========================================================
-- 7. Cascade a user disable down to their shops and
--    delivery-personnel status
--    ("active_status ... -- call a trigger to disable shops, delivery_personnel")
-- =========================================================
CREATE OR REPLACE TRIGGER trg_disable_user_dependents
AFTER UPDATE ON users FOR EACH ROW
WHEN (NEW.active_status = 'disabled' AND OLD.active_status <> 'disabled')
BEGIN
    -- disable any shops this user owns
    UPDATE shops
    SET active_status = 'disabled'
    WHERE owner = :NEW.user_id
      AND active_status <> 'disabled';

    -- if this user is also delivery personnel, take them off duty
    UPDATE delivery_personnel
    SET active_status = 'unavailable'
    WHERE delivery_person_id = :NEW.user_id
      AND active_status <> 'unavailable';
END;
/

-- =========================================================
-- 7b. Undo the shop half of the cascade when a user is restored
--     An administrator un-banning a user expects the user's shops to come back.
--     Listings deliberately stay discontinued (fn_discontinue_products_on_shop_disable
--     is one-way), so a vendor consciously relists rather than having retired
--     listings silently resurrected.
--     delivery_personnel is deliberately left alone: the disable direction sets a
--     courier 'unavailable', which also releases their in-flight orders, and
--     returning them to 'available' would put them back on duty without opting in.
--     Couriers set their own availability from the delivery workspace.
-- =========================================================
CREATE OR REPLACE TRIGGER trg_enable_user_dependents
AFTER UPDATE ON users FOR EACH ROW
WHEN (NEW.active_status = 'active' AND OLD.active_status <> 'active')
BEGIN
    UPDATE shops
    SET active_status = 'active'
    WHERE owner = :NEW.user_id
      AND active_status = 'disabled';
END;
/

-- A completed delivery is the proof of purchase for a product review.
CREATE OR REPLACE TRIGGER trg_verify_product_review_purchase
BEFORE INSERT OR UPDATE ON product_reviews FOR EACH ROW
DECLARE
    v_proven NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_proven
    FROM orders o
    JOIN order_items oi ON oi.order_id = o.order_id
    JOIN users u ON u.user_id = o.user_id
    JOIN roles r ON r.role_id = u.user_role
    WHERE o.user_id = :NEW.user_id AND oi.prod_id = :NEW.prod_id
      AND o.order_status = 'delivered' AND r.role_name = 'customer';

    IF v_proven = 0 THEN
        RAISE_APPLICATION_ERROR(-20002,
            'Only customers with a delivered purchase of this listing can review it.');
    END IF;

    :NEW.last_modified := LOCALTIMESTAMP;
END;
/

-- The same rule for shop reviews: a delivered order containing one of the
-- shop's listings is the proof of purchase.
CREATE OR REPLACE TRIGGER trg_verify_shop_review_purchase
BEFORE INSERT OR UPDATE ON shop_reviews FOR EACH ROW
DECLARE
    v_proven NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_proven
    FROM orders o
    JOIN order_items oi ON oi.order_id = o.order_id
    JOIN products p ON p.prod_id = oi.prod_id
    JOIN users u ON u.user_id = o.user_id
    JOIN roles r ON r.role_id = u.user_role
    WHERE o.user_id = :NEW.user_id
      AND p.shop_id = :NEW.shop_id
      AND o.order_status = 'delivered'
      AND r.role_name = 'customer';

    IF v_proven = 0 THEN
        RAISE_APPLICATION_ERROR(-20003,
            'Only customers with a delivered order from this shop can review it.');
    END IF;

    :NEW.last_modified := LOCALTIMESTAMP;
END;
