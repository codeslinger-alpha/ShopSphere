-- Canonical fresh-database definition, for Oracle. Run once in an empty schema.
-- Descriptions may contain Markdown. Demo rows are loaded separately.
--
-- Every statement is followed by a line holding only "/", the convention
-- SQL*Plus uses and the one scripts/init.js splits the file on. Oracle has no
-- equivalent of PostgreSQL's simple protocol, where a whole file of statements
-- can be handed over as one string, so the file has to be cut up first.
--
-- Four spellings recur below, and they are Oracle's doing rather than this
-- schema's:
--
--   * TEXT is CLOB. VARCHAR2 stops at 4000 bytes, and the descriptions,
--     reviews and image lists this schema stores are unbounded.
--   * boolean is NUMBER(1) with a CHECK, which is what Oracle has instead.
--     src/db/execute.js turns those back into true and false on the way out,
--     so the API still speaks in booleans.
--   * CURRENT_TIMESTAMP is LOCALTIMESTAMP. The first is a TIMESTAMP WITH TIME
--     ZONE and would be converted on the way into every TIMESTAMP column; the
--     second is already the type these columns hold.
--   * PostgreSQL's ON DELETE RESTRICT is written as nothing at all. NO ACTION
--     is Oracle's only behaviour for a foreign key, and the deletes this schema
--     actually cares about are refused by triggers outright.
--
-- Identity columns are GENERATED BY DEFAULT ON NULL rather than GENERATED
-- ALWAYS. The demo rows in sql/test_insert name their own courier and country
-- ids — the courier rows are keyed by user id, so they have to — and a schema
-- that refused them would make the seed file unwritable.

